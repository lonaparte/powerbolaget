def glyph(rows):
    pen=TTGlyphPen(None)
    for r,row in enumerate(rows):
        y0=(6-r)*PX;x=0
        while x<len(row):
            if row[x]!='#':x+=1;continue
            end=x
            while end<len(row) and row[end]=='#':end+=1
            pen.moveTo((x*PX,y0));pen.lineTo((x*PX,y0+PX));pen.lineTo((end*PX,y0+PX));pen.lineTo((end*PX,y0));pen.closePath();x=end
    return pen.glyph()
def build():
    order=['.notdef','space'];cmap={32:'space'};glyphs={'.notdef':glyph(['#####','#...#','#...#','#...#','#...#','#...#','#####']),'space':glyph([])};metrics={'.notdef':(600,0),'space':(400,0)}
    for ch,spec in G.items():
        rows=spec.split(' ');name=f'u{ord(ch):04X}';order.append(name);cmap[ord(ch)]=name
        glyphs[name]=glyph(rows);metrics[name]=((len(rows[0])+1)*PX,0)
        if ch.isalpha() and ch.lower()!=ch:cmap[ord(ch.lower())]=name
    fb=FontBuilder(800,isTTF=True);fb.setupGlyphOrder(order);fb.setupCharacterMap(cmap);fb.setupGlyf(glyphs);fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800,descent=-200)
    fb.setupNameTable(dict(familyName='Powerbolaget Pixel',styleName='Regular',uniqueFontIdentifier='Powerbolaget Pixel 0.0.1',fullName='Powerbolaget Pixel',psName='PowerbolagetPixel-Regular',version='Version 0.0.1',licenseDescription='MIT License, part of Powerbolaget'))
    fb.setupOS2(sTypoAscender=800,sTypoDescender=-200,sTypoLineGap=0,usWinAscent=800,usWinDescent=200,sxHeight=700,sCapHeight=700)
    fb.setupPost();fb.font.flavor='woff';fb.save(OUT)
    print(f'{OUT}: {len(order)} glyphs, {OUT.stat().st_size} bytes')
if __name__=='__main__':build()
